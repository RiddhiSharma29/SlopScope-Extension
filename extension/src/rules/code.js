/* Code / source-level rules. Reads the live DOM, class names, comments and meta tags. */
(function () {
  const S = window.SlopScope;
  const U = S.util;
  const R = U.register;

  R({
    id: 'code-generator-fingerprint', cat: 'code', sev: 3,
    title: 'AI app-builder fingerprints',
    why: 'Attributes, scripts, titles and favicons left behind by Lovable, v0, Bolt, Vite and Next.js starters.',
    run(ctx) {
      const out = [];
      const add = (detail, el) => out.push({ el, detail });
      const lov = document.querySelector('[data-lov-id], [data-lov-name]');
      if (lov) add('Lovable data-lov-* attributes present', lov);
      for (const s of document.querySelectorAll('script[src]')) {
        if (/gptengineer|lovable/i.test(s.src)) add(`Script from ${U.snippet(s.src, 60)}`, undefined);
      }
      if (/^(React App|Vite \+ React|Vite App|Create Next App|Next\.js App|Vite \+ TS)$/i.test((document.title || '').trim())) add(`Default title: "${document.title}"`);
      const desc = document.querySelector('meta[name="description"]');
      if (desc && /generated by create next app|created using create-react-app/i.test(desc.content)) add('Starter-template meta description');
      const gen = document.querySelector('meta[name="generator"]');
      if (gen && /\b(v0|bolt|lovable|replit|cursor)\b/i.test(gen.content)) add(`Generator meta: ${gen.content}`);
      if (document.querySelector('link[rel~="icon"][href*="vite.svg"]')) add('Default Vite favicon');
      if (/\b(built with|made with|edit with) (lovable|bolt|v0)\b/i.test(ctx.text)) add('"Built with" AI-builder badge');
      return out.slice(0, 8);
    },
  });

  R({
    id: 'code-tailwind-gradient', cat: 'code', sev: 2,
    title: 'Tailwind purple/pink gradient utility classes',
    why: 'from-purple-500 to-pink-500 style gradients are the single most copied generated-UI recipe.',
    run(ctx) {
      const out = [];
      const re = /\b(?:from|via|to)-(?:purple|violet|indigo|fuchsia|pink)-\d{3}\b/;
      for (const el of ctx.els) {
        if (out.length >= 10) break;
        const cls = el.getAttribute('class') || '';
        if (re.test(cls)) out.push({ el, detail: cls.match(re)[0] });
      }
      return out;
    },
  });

  R({
    id: 'code-shadcn-defaults', cat: 'code', sev: 1,
    title: 'Unthemed shadcn/ui defaults',
    why: 'Many muted-foreground / data-slot elements suggest the stock component kit was used without customisation.',
    run(ctx) {
      const hits = ctx.els.filter((e) => /\btext-muted-foreground\b/.test(e.getAttribute('class') || '') || e.hasAttribute('data-slot'));
      return hits.length >= 5 ? [{ el: hits[0], detail: `${hits.length} shadcn-style elements` }] : [];
    },
  });

  R({
    id: 'code-dead-links', cat: 'code', sev: 2,
    title: 'Dead placeholder links',
    why: 'Generated pages are full of href="#" and javascript:void(0) that go nowhere.',
    run(ctx) {
      const dead = [...document.querySelectorAll('a')].filter((a) => {
        const h = (a.getAttribute('href') || '').trim();
        return h === '#' || h === '' || /^javascript:\s*void/i.test(h);
      });
      return dead.length >= 4 ? [{ el: dead[0], detail: `${dead.length} links with no real destination` }] : [];
    },
  });

  R({
    id: 'code-no-landmarks', cat: 'code', sev: 2,
    title: 'Div soup with no landmarks',
    why: 'Large pages built from divs only, with no header/main/nav/footer, lack semantic structure.',
    run(ctx) {
      const divs = document.querySelectorAll('div').length;
      const land = document.querySelectorAll('header, main, nav, footer, section, article, aside').length;
      const out = [];
      if (divs >= 60 && land === 0) out.push({ detail: `${divs} divs, 0 semantic landmarks` });
      const h1s = document.querySelectorAll('h1').length;
      if (divs >= 20 && h1s !== 1) out.push({ detail: `${h1s} <h1> elements (expected exactly 1)` });
      return out;
    },
  });

  R({
    id: 'code-section-comments', cat: 'code', sev: 1,
    title: 'Section-label HTML comments',
    why: 'Comments such as <!-- Hero Section --> and <!-- Features --> are typical of unminified generated markup.',
    run() {
      const out = [];
      const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_COMMENT);
      let n, label = 0, todo = 0;
      while ((n = walker.nextNode())) {
        const t = n.nodeValue.trim();
        if (/^(hero|features?|pricing|testimonials?|cta|call to action|footer|navigation|header|faq|stats?)\s*(section)?$/i.test(t)) label++;
        if (/\b(TODO|Lorem|your (content|text) here|replace (this|with))\b/i.test(t)) todo++;
      }
      if (label >= 3) out.push({ detail: `${label} section-label comments` });
      if (todo >= 1) out.push({ detail: `${todo} leftover TODO/placeholder comments` });
      return out;
    },
  });
})();
